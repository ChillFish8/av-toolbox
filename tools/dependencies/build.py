#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""Builds the optional dependencies declared under dependencies/."""

import argparse
import hashlib
import shutil
import subprocess
import sys
import tempfile
import tomllib
import urllib.request
import zipfile
from dataclasses import dataclass
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[2]
LOCK_HEADER = "# Generated by tools/dependencies/build.py. Do not edit by hand.\n"
ZIP_TIMESTAMP = (1980, 1, 1, 0, 0, 0)


class BuildError(Exception):
    pass


@dataclass(frozen=True)
class Source:
    name: str
    url: str
    sha256: str


@dataclass(frozen=True)
class Dependency:
    identifier: str
    directory: Path
    sources: list[Source]
    files: list[str]
    builtin: list[str]


def load_dependency(directory: Path) -> Dependency:
    manifest_path = directory / "dependency.toml"
    with manifest_path.open("rb") as manifest_file:
        manifest = tomllib.load(manifest_file)

    sources = [Source(entry["name"], entry["url"], entry["sha256"]) for entry in manifest["sources"]]
    files = list(manifest["files"])
    builtin = list(manifest.get("builtin", []))

    unlisted = [name for name in builtin if name not in files]
    if unlisted:
        raise BuildError(f"{directory.name}: builtin files {unlisted} are not listed in files")

    return Dependency(manifest["identifier"], directory, sources, files, builtin)


def discover(dependencies_root: Path) -> list[Dependency]:
    manifests = sorted(dependencies_root.glob("*/dependency.toml"))
    dependencies = [load_dependency(manifest.parent) for manifest in manifests]
    check_builtin_names(dependencies)

    return dependencies


def check_builtin_names(dependencies: list[Dependency]) -> None:
    """Refuses two dependencies declaring the same builtin file, as every builtin shares one directory."""
    owners: dict[str, str] = {}

    for dependency in dependencies:
        for name in dependency.builtin:
            if name in owners:
                raise BuildError(f"{name} is a builtin of both {owners[name]} and {dependency.identifier}")

            owners[name] = dependency.identifier


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()

    with path.open("rb") as source:
        while chunk := source.read(1 << 20):
            digest.update(chunk)

    return digest.hexdigest()


def fetch(source: Source, cache: Path) -> Path:
    cache.mkdir(parents=True, exist_ok=True)
    target = cache / source.name

    if target.exists() and sha256_of(target) == source.sha256:
        return target

    partial = cache / f"{source.name}.partial"
    with urllib.request.urlopen(source.url) as response, partial.open("wb") as written:
        shutil.copyfileobj(response, written)

    found = sha256_of(partial)
    if found != source.sha256:
        partial.unlink()
        raise BuildError(f"{source.name} from {source.url} has sha256 {found}, expected {source.sha256}")

    partial.replace(target)
    return target


def convert(dependency: Dependency, sources_dir: Path, output_dir: Path) -> None:
    script = dependency.directory / "convert.py"
    command = ["uv", "run", "--script", str(script), str(sources_dir), str(output_dir)]
    try:
        subprocess.run(command, check=True)
    except subprocess.CalledProcessError as error:
        message = f"{dependency.identifier}: convert.py exited with status {error.returncode}"
        raise BuildError(message) from error

    written = sorted(path.name for path in output_dir.iterdir())
    expected = sorted(dependency.files)
    if written != expected:
        raise BuildError(f"{dependency.identifier}: convert.py wrote {written}, expected {expected}")


def write_zip(dependency: Dependency, output_dir: Path, zip_path: Path) -> None:
    licence = dependency.directory / "LICENSE"
    if not licence.is_file():
        raise BuildError(f"{dependency.identifier}: LICENSE is missing")

    entries = [(name, output_dir / name) for name in dependency.files]
    entries.append(("LICENSE", licence))
    entries.sort()

    zip_path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zip_path, "w") as archive:
        for name, path in entries:
            info = zipfile.ZipInfo(name, ZIP_TIMESTAMP)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            content = path.read_bytes()
            archive.writestr(info, content)


def read_lock(lock_path: Path) -> dict[str, dict[str, str]]:
    if not lock_path.exists():
        return {}

    with lock_path.open("rb") as lock_file:
        return tomllib.load(lock_file)


def render_lock(lock: dict[str, dict[str, str]]) -> str:
    lines = [LOCK_HEADER]

    for identifier in sorted(lock):
        lines.append(f"\n[{identifier}]\n")

        for name, sha256 in lock[identifier].items():
            lines.append(f'"{name}" = "{sha256}"\n')

    return "".join(lines)


def build(identifiers: list[str], repository: Path, check: bool) -> int:
    dependencies_root = repository / "dependencies"
    available = discover(dependencies_root)
    known = {dependency.identifier for dependency in available}

    unknown = [identifier for identifier in identifiers if identifier not in known]
    if unknown:
        raise BuildError(f"no dependency is named {unknown}. The dependencies are {sorted(known)}")

    chosen = [dependency for dependency in available if not identifiers or dependency.identifier in identifiers]
    target = repository / "target" / "dependencies"
    lock_path = dependencies_root / "dependencies.lock"
    builtin_root = repository / "av-toolbox-models" / "builtin"
    builtin_files: dict[str, bytes] = {}

    # A full build writes every section again, so sections of removed dependencies are dropped.
    lock = {}
    if identifiers:
        lock = read_lock(lock_path)

    for dependency in chosen:
        with tempfile.TemporaryDirectory() as work_name:
            work = Path(work_name)
            sources_dir = work / "sources"
            output_dir = work / "output"
            sources_dir.mkdir()
            output_dir.mkdir()

            cache = target / "cache" / dependency.identifier
            for source in dependency.sources:
                fetched = fetch(source, cache)
                shutil.copyfile(fetched, sources_dir / source.name)

            convert(dependency, sources_dir, output_dir)

            zip_path = target / f"optional-dependency-{dependency.identifier}.zip"
            write_zip(dependency, output_dir, zip_path)

            lock[dependency.identifier] = {name: sha256_of(output_dir / name) for name in dependency.files}

            for name in dependency.builtin:
                builtin_path = output_dir / name
                builtin_files[name] = builtin_path.read_bytes()

    rendered = render_lock(lock)

    if check:
        return report_differences(lock_path, rendered, builtin_root, builtin_files)

    lock_path.write_text(rendered)
    builtin_root.mkdir(parents=True, exist_ok=True)

    for name, content in builtin_files.items():
        builtin_path = builtin_root / name
        builtin_path.write_bytes(content)

    return 0


def report_differences(lock_path: Path, rendered: str, builtin_root: Path, builtin_files: dict[str, bytes]) -> int:
    differences = []

    current_lock = lock_path.read_text() if lock_path.exists() else ""
    if current_lock != rendered:
        lock_name = str(lock_path)
        differences.append(lock_name)

    for name, content in builtin_files.items():
        builtin_path = builtin_root / name
        current = builtin_path.read_bytes() if builtin_path.exists() else None

        if current != content:
            builtin_name = str(builtin_path)
            differences.append(builtin_name)

    for difference in differences:
        print(f"out of date: {difference}", file=sys.stderr)

    return 1 if differences else 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Builds the optional dependencies declared under dependencies/.")
    parser.add_argument("identifiers", nargs="*", help="the dependencies to build, every one when none are given")
    parser.add_argument("--check", action="store_true", help="fail if the lock or a builtin file would change")
    arguments = parser.parse_args()

    try:
        return build(arguments.identifiers, REPOSITORY, arguments.check)
    except BuildError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    status = main()
    sys.exit(status)
